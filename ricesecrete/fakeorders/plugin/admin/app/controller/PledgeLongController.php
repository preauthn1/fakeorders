<?php

namespace plugin\admin\app\controller;

use app\model\pledge\PledgeLongModel;
use app\model\user\UserModel;
use app\services\UserServices;
use plugin\admin\app\model\User;
use support\exception\BusinessException;
use support\Request;
use support\Response;
use Throwable;

/**
 * 理财管理
 */
class PledgeLongController extends Crud
{

    /**
     * @var User
     */
    protected $model = null;

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new PledgeLongModel();
    }


    /**
     * 查询
     * @param Request $request
     * @return Response
     */
    public function select(Request $request): Response
    {
        [$where, $format, $limit, $field, $order] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'DESC';
        }
        if (empty($field)) {
            $field = 'id';
        }
        $username = $request->get('username', '');
        if (!empty($username)) {
            $ids = UserModel::where('username', 'like', '%' . $username . '%')->column('id');
            if (!empty($ids)) {
                $where['user_id'][0] = 'in';
                $where['user_id'][1] = $ids;
            } else {
                $where['user_id'] = 0;
            }
            unset($where['username']);
        }
        $query = $this->doSelect($where, $field, $order);
        $methods = [
            'select' => 'formatSelect',
            'tree' => 'formatTree',
            'table_tree' => 'formatTableTree',
            'normal' => 'formatNormal',
        ];
        $paginator = $query->paginate($limit);
        $total = $paginator->total();
        $items = $paginator->items();
        foreach ($items as &$item) {
            $item['user_info'] = UserServices::getUserInfo($item['user_id']);
            $end_time = date('Y-m-d H:i:s', $item['end_time']);
            $item['end_time_str'] = $end_time;
        }
        // TODO: Change the autogenerated stub
        return call_user_func([$this, $methods[$format]], $items, $total);
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {
        return raw_view('pledgelong/index');
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            return parent::insert($request);
        }
        return raw_view('pledgelong/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
            return parent::update($request);
        }
        return raw_view('pledgelong/update');
    }

}
