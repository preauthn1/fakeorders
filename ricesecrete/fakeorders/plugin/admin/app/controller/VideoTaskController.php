<?php

namespace plugin\admin\app\controller;

use app\model\user\UserModel;
use app\model\video\VideoModel;
use app\model\video\VideoTaskModel;
use app\services\VideoTaskServices;
use support\exception\BusinessException;
use support\Request;
use support\Response;
use Throwable;

/**
 * 视频任务管理
 */
class VideoTaskController extends Crud
{

    /**
     * @var VideoTaskModel
     */
    protected $model = null;

    /**
     * 查询
     * @param Request $request
     * @return Response
     */
    public function select(Request $request): Response
    {
        [$where, $format, $limit, $field, $order] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'desc';
        }
        if (empty($field)) {
            $field = "id";
        }
        $username = $request->get('username', '');
        if (!empty($username)) {
            $ids = UserModel::where('username', 'like', '%' . $username . '%')->column('id');
            if (!empty($ids)) {
                $where['user_id'][0] = 'in';
                $where['user_id'][1] = $ids;
            }
            unset($where['username']);
        }
        $query = $this->doSelect($where, $field, $order);
        $methods = [
            'select' => 'formatSelect',
            'tree' => 'formatTree',
            'table_tree' => 'formatTableTree',
            'normal' => 'formatNormal',
        ];
        $paginator = $query->paginate($limit);
        $total = $paginator->total();
        $items = $paginator->items();
        foreach ($items as &$item) {
            $user_info = [
                'id' => 0,
                'username' => '未知',
            ];
            $item['user_info'] = empty($item['user_id']) ? $user_info : UserModel::where('id', $item['user_id'])->field(['id', 'username'])->find();
            $item['video_info'] = empty($item['video_id']) ? [] : VideoModel::where('id', $item['video_id'])->field(['id', 'title'])->find();
        }
        // TODO: Change the autogenerated stub
        return call_user_func([$this, $methods[$format]], $items, $total);
    }

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new VideoTaskModel();
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {

        return raw_view('videotask/index');
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            $data = $this->insertInput($request);
            $ret = VideoTaskServices::addTask($data['user_id'], $data['video_id']);
            if ($ret['code'] == 0) {
                return $this->json(0, 'ok', ['id' => $ret['data']]);
            }
            return $this->json(1, $ret['msg']);
        }
        return raw_view('videotask/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
            [$id, $data] = $this->updateInput($request);
            $ret = VideoTaskServices::updateStatus($id, $data['status']);
            if (!$ret) {
                return $this->json(1, '更新失败');
            }
            return $this->json(0);
        }
        return raw_view('videotask/update');
    }

}
