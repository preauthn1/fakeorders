<?php

namespace plugin\admin\app\controller;

use app\common\push\PushApi;
use app\model\user\UserModel;
use app\services\UserServices;
use app\services\UserWalletServices;
use plugin\admin\app\model\User;
use support\exception\BusinessException;
use support\Request;
use support\Response;
use Throwable;

/**
 * 用户管理
 */
class UserController extends Crud
{

    /**
     * 导出文件
     * @var string
     */
    protected $export_fun = "\app\services\UserServices::exportFile";
    /**
     * @var User
     */
    protected $model = null;

    /**
     * 构造函数
     * @return void
     */
    public function __construct()
    {
        $this->model = new UserModel();
    }

    /**
     * 浏览
     * @param Request $request
     * @return Response
     */
    public function select(Request $request): Response
    {
        [$where, $format, $limit, $field, $order] = $this->selectInput($request);
        if ($request->get('order', '') == '') {
            $order = 'desc';
        }
        if (empty($field)) {
            $field = "id";
        }
        $query = $this->doSelect($where, $field, $order);
        [$items, $total] = $this->doData($query, $limit);
        // TODO: Change the autogenerated stub
        foreach ($items as &$item) {
            $tree = $item['tree'];
            //去除数组中的空元素
            $tree_arr = array_filter(explode('/', $tree));
            //去掉最后一个元素
            array_pop($tree_arr);
            for ($i = 0; $i <= 9; $i++) {
                $item['leader' . $i . '_user'] = "-/-";
            }
            if (!empty($tree_arr)) {
                //获取第一个元素
                $first_element = array_shift($tree_arr);
                $item['leader0_user'] = UserServices::getInvUser($first_element);
                $tree_arr = array_reverse($tree_arr);
                for ($i = 1; $i <= 9; $i++) {
                    if (isset($tree_arr[$i])) {
                        $item['leader' . $i . '_user'] = UserServices::getInvUser($tree_arr[$i]);
                    }
                }
            }
            $item['online'] = PushApi::getOnlineUser($item['id']);
            $item['recharge_address'] = UserWalletServices::getWalletOne($item['id']);
            $item['withdraw_address'] = UserWalletServices::getWalletOne($item['id'], 1, '');
        }
        return call_user_func([$this, "formatNormal"], $items, $total);
    }

    /**
     * 浏览
     * @return Response
     * @throws Throwable
     */
    public function index(): Response
    {
        return raw_view('user/index');
    }

    /**
     * 下级用户
     * @param Request $request
     * @return Response
     * @throws Throwable
     */
    public function junior(Request $request): Response
    {
        $top_id = $request->get('top_id', '');
        return raw_view('user/junior', ['top_id' => $top_id]);
    }

    /**
     * 插入
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function insert(Request $request): Response
    {
        if ($request->method() === 'POST') {
            $params = $request->post();
            $data_json = UserServices::addUser($params);
            return json($data_json);
        }
        return raw_view('user/insert');
    }

    /**
     * 更新
     * @param Request $request
     * @return Response
     * @throws BusinessException|Throwable
     */
    public function update(Request $request): Response
    {
        if ($request->method() === 'POST') {
            return parent::update($request);
        }
        return raw_view('user/update');
    }

    /**
     * 删除
     * @param Request $request
     * @return Response
     */
    public function delete(Request $request): Response
    {
        return $this->json(1, '删除不允许');
//        return parent::delete($request); // TODO: Change the autogenerated stub
    }
}
